// Package terraform generates a Terraform (and OpenTofu) module from a
// docuconf contract, as spec/IAC.md describes: one argument per input,
// typed and constrained like the input and saying how it is set, and
// outputs that render the inputs into the blocks a workload takes.
//
// This version covers the kubernetes target and environment variables.
// File inputs and overlays are rejected with a clear error until the
// module can render their volumes and ConfigMaps.
package terraform

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math/big"
	"regexp"
	"sort"
	"strings"

	"github.com/hashicorp/hcl/v2/hclwrite"
)

// Header starts every generated .tf file, and MarkdownHeader the README.
const (
	Header         = "# Code generated by docuconf. DO NOT EDIT.\n"
	MarkdownHeader = "<!-- Code generated by docuconf. DO NOT EDIT. -->\n"
)

// Options configure a generated module.
type Options struct {
	// Targets are the workload kinds to render for. Only "kubernetes" is
	// implemented.
	Targets []string
	// GeneratorVersion is the docuconf CLI's version, recorded in
	// docuconf.json.
	GeneratorVersion string
}

// Contract is the part of a contract the generator reads.
type Contract struct {
	Name     string
	Vars     []Var // in contract order
	Profiles *Profiles
	Files    []string
	Overlays []string
	JSON     []byte // the contract as JSON, as docuconf helm writes it
}

// Var is one contract variable.
type Var struct {
	Name   string
	Raw    map[string]any
	Type   string
	Secret bool
}

// Profiles is the contract's profiles block.
type Profiles struct {
	Selector string
	Default  string
	Defaults map[string]map[string]any
}

// Parse reads a contract's JSON, keeping the order of vars.
func Parse(contractJSON []byte) (*Contract, error) {
	var doc struct {
		Metadata struct {
			Name string `json:"name"`
		} `json:"metadata"`
		Vars     map[string]map[string]any `json:"vars"`
		Files    map[string]any            `json:"files"`
		Overlays map[string]any            `json:"overlays"`
		Profiles *struct {
			Selector string                    `json:"selector"`
			Default  string                    `json:"default"`
			Defaults map[string]map[string]any `json:"defaults"`
		} `json:"profiles"`
	}
	dec := json.NewDecoder(bytes.NewReader(contractJSON))
	dec.UseNumber()
	if err := dec.Decode(&doc); err != nil {
		return nil, fmt.Errorf("reading the contract: %w", err)
	}
	order, err := varOrder(contractJSON)
	if err != nil {
		return nil, err
	}
	c := &Contract{Name: doc.Metadata.Name, JSON: contractJSON}
	for _, n := range order {
		raw := doc.Vars[n]
		c.Vars = append(c.Vars, Var{Name: n, Raw: raw, Type: str(raw, "type"), Secret: boolean(raw, "secret") || str(raw, "type") == "keySet"})
	}
	for n := range doc.Files {
		c.Files = append(c.Files, n)
	}
	for n := range doc.Overlays {
		c.Overlays = append(c.Overlays, n)
	}
	sort.Strings(c.Files)
	sort.Strings(c.Overlays)
	if doc.Profiles != nil {
		c.Profiles = &Profiles{Selector: doc.Profiles.Selector, Default: doc.Profiles.Default, Defaults: doc.Profiles.Defaults}
	}
	return c, nil
}

// varOrder returns the keys of the contract's vars object in the order the
// JSON holds them, which is the contract's order.
func varOrder(contractJSON []byte) ([]string, error) {
	var top map[string]json.RawMessage
	if err := json.Unmarshal(contractJSON, &top); err != nil {
		return nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(top["vars"]))
	if t, err := dec.Token(); err != nil || t != json.Delim('{') {
		return nil, fmt.Errorf("reading the contract: vars is not an object")
	}
	var out []string
	for dec.More() {
		t, err := dec.Token()
		if err != nil {
			return nil, err
		}
		out = append(out, t.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// Generate writes the module's files, keyed by file name.
func Generate(c *Contract, opt Options) (map[string][]byte, error) {
	if len(opt.Targets) == 0 {
		opt.Targets = []string{"kubernetes"}
	}
	for _, t := range opt.Targets {
		if t != "kubernetes" {
			return nil, fmt.Errorf("target %q is not supported yet; supported: kubernetes", t)
		}
	}
	if len(c.Files) > 0 {
		return nil, fmt.Errorf("file inputs (%s) are not supported by docuconf terraform yet: it renders environment variables only", strings.Join(c.Files, ", "))
	}
	if len(c.Overlays) > 0 {
		return nil, fmt.Errorf("config-file overlays (%s) are not supported by docuconf terraform yet: it renders environment variables only", strings.Join(c.Overlays, ", "))
	}
	g := &gen{c: c}
	for _, v := range c.Vars {
		if err := g.checkSupported(v); err != nil {
			return nil, err
		}
	}
	sum := sha256.Sum256(c.JSON)
	digest := "sha256:" + hex.EncodeToString(sum[:])
	meta, err := json.MarshalIndent(map[string]any{
		"apiVersion":     "docuconf.dev/v1alpha1",
		"kind":           "TerraformModule",
		"generator":      map[string]any{"name": "docuconf", "version": opt.GeneratorVersion},
		"targets":        opt.Targets,
		"contractDigest": digest,
		"contract":       json.RawMessage(c.JSON),
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"versions.tf":   hclwrite.Format([]byte(Header + "\nterraform {\n  # optional() attributes, check blocks and output preconditions.\n  required_version = \">= 1.5.0\"\n}\n")),
		"variables.tf":  hclwrite.Format(g.variables()),
		"render.tf":     hclwrite.Format(g.render()),
		"outputs.tf":    hclwrite.Format(g.outputs(digest)),
		"docuconf.json": append(meta, '\n'),
		"README.md":     g.readme(),
	}, nil
}

type gen struct {
	c *Contract
}

func (g *gen) checkSupported(v Var) error {
	switch v.Type {
	case "string", "int", "float", "bool", "duration", "url", "enum", "list", "json", "keySet":
		return nil
	}
	return fmt.Errorf("%s: type %q is not supported by docuconf terraform", v.Name, v.Type)
}

// sources lists the argument's attributes: the ways the input can be set
// on the kubernetes target (SPEC.md 4.5 and 6).
func (g *gen) sources(v Var) []string {
	if v.Secret {
		return []string{"secret", "injected"}
	}
	s := []string{"value"}
	if v.Type != "list" {
		s = append(s, "config_map")
	}
	if v.Type == "string" {
		s = append(s, "field")
	}
	if v.Type == "int" {
		s = append(s, "resource_field")
	}
	return append(s, "injected")
}

func valueType(v Var) string {
	switch v.Type {
	case "int", "float":
		return "number"
	case "bool":
		return "bool"
	case "list":
		if str(v.Raw, "items") == "int" {
			return "list(number)"
		}
		return "list(string)"
	case "json":
		return "any"
	}
	return "string"
}

var sourceTypes = map[string]string{
	"secret":         "object({ name = string, key = string })",
	"config_map":     "object({ name = string, key = string })",
	"field":          "object({ field_path = string })",
	"resource_field": "object({ resource = string, divisor = optional(string), container_name = optional(string) })",
	"injected":       "object({ provider = string, ref = optional(string), pod_annotations = optional(map(string), {}), pod_labels = optional(map(string), {}) })",
}

// required reports whether the module must be given the input. A required
// input a profile can supply is optional here: which profile applies is
// only known from the selector's value (spec/IAC.md 4.3).
func (g *gen) required(v Var) bool {
	if !boolean(v.Raw, "required") {
		return false
	}
	if p := g.c.Profiles; p != nil {
		for _, m := range p.Defaults {
			if _, ok := m[v.Name]; ok {
				return false
			}
		}
	}
	return true
}

func (g *gen) variables() []byte {
	var b strings.Builder
	b.WriteString(Header)
	for _, v := range g.c.Vars {
		fmt.Fprintf(&b, "\nvariable %q {\n", v.Name)
		fmt.Fprintf(&b, "  description = %s\n", hclString(describeVar(v)))
		b.WriteString("  type = object({\n")
		for _, s := range g.sources(v) {
			t := sourceTypes[s]
			if s == "value" {
				t = valueType(v)
			}
			fmt.Fprintf(&b, "    %-14s = optional(%s)\n", s, t)
		}
		b.WriteString("  })\n")
		if g.required(v) {
			b.WriteString("  nullable = false\n")
		} else {
			b.WriteString("  default  = null\n")
		}
		for _, c := range g.checks(v, "var."+v.Name) {
			fmt.Fprintf(&b, "\n  validation {\n    condition     = %s\n    error_message = %s\n  }\n", c.cond, c.msg)
		}
		b.WriteString("}\n")
		if d, ok := v.Raw["deprecated"].(map[string]any); ok {
			fmt.Fprintf(&b, "\ncheck %q {\n  assert {\n    condition     = var.%s == null\n    error_message = %s\n  }\n}\n",
				"deprecated_"+v.Name, v.Name, hclString(fmt.Sprintf("warning: %s is deprecated, and the platform still sets it: %s", v.Name, str(d, "message"))))
		}
	}
	b.WriteString(`
variable "docuconf_options" {
  description = "Settings for the module that are not contract inputs (spec/IAC.md 4.2)."
  type = object({
    pod_annotations = optional(map(string), {}) # shared by every injected input (SPEC.md 4.5.2)
    pod_labels      = optional(map(string), {})
    unmanaged_env   = optional(list(string), []) # env the platform sets itself, ignored by docuconf lint
    allow_env_from  = optional(bool, false)
  })
  default  = {}
  nullable = false

  validation {
    condition = alltrue([for k, v in merge(var.docuconf_options.pod_annotations, var.docuconf_options.pod_labels) :
    length(regexall("\\{(input|path|dir|file)\\}", "${k}${v}")) == 0])
    error_message = "docuconf_options: the shared pod annotations and labels cannot use placeholders; put {input}, {path}, {dir} and {file} on an input's injected source"
  }
`)
	b.WriteString("}\n")
	return []byte(b.String())
}

func describeVar(v Var) string {
	d := str(v.Raw, "description")
	var tags []string
	if boolean(v.Raw, "required") {
		tags = append(tags, "required")
	}
	if v.Secret {
		tags = append(tags, "secret")
	}
	tags = append(tags, v.Type)
	return fmt.Sprintf("%s (%s)", d, strings.Join(tags, ", "))
}

// check is one validation: an HCL condition and an HCL error message.
type check struct{ cond, msg string }

// checks returns the argument's validations, written against ref (var.X).
// Each repeats what #Validate and docuconf vet check, with vet's message.
func (g *gen) checks(v Var, ref string) []check {
	n := v.Name
	srcs := g.sources(v)
	var out []check
	list := make([]string, len(srcs))
	copy(list, srcs)
	out = append(out, check{
		cond: fmt.Sprintf("%s == null ? true : length([for k, s in %s : k if s != null]) == 1", ref, ref),
		msg:  hclString(fmt.Sprintf("%s: set exactly one of %s", n, orList(list))),
	})
	inj := ref + ".injected"
	out = append(out,
		check{
			cond: guard(ref, inj, fmt.Sprintf(`can(regex("^[a-z0-9]([-a-z0-9.]{0,61}[a-z0-9])?$", %s.provider))`, inj)),
			msg:  hclString(n + ": injected.provider must name the injector as a lowercase label, such as bank-vaults"),
		},
		check{
			cond: guard(ref, inj, fmt.Sprintf(`%s.ref == null ? true : %s.ref != ""`, inj, inj)),
			msg:  hclString(n + ": injected.ref cannot be empty; leave it out when the injector sets the variable itself"),
		},
		check{
			cond: guard(ref, inj, fmt.Sprintf(`alltrue([for k, x in merge(%s.pod_annotations, %s.pod_labels) : length(regexall("\\{(path|dir|file)\\}", "${k}${x}")) == 0])`, inj, inj)),
			msg:  hclString(n + ": pod annotations and labels use {path}, {dir} or {file}, which only a file input defines; a variable has {input}"),
		},
	)
	if (v.Type == "list" || v.Type == "keySet") && str(v.Raw, "encoding") == "indexed" {
		out = append(out, check{
			cond: guard(ref, inj, inj+".ref == null"),
			msg:  hclString(n + ": an indexed list is spread over NAME__0, NAME__1, …, so one injected reference cannot carry it; let the injector set the variables, without ref"),
		})
	}
	if has(srcs, "field") {
		f := ref + ".field"
		out = append(out, check{
			cond: guard(ref, f, fmt.Sprintf(`can(regex("^(metadata\\.(name|namespace|uid)|spec\\.(nodeName|serviceAccountName)|status\\.(hostIP|podIP)|metadata\\.(labels|annotations)\\['[^']+'\\])$", %s.field_path))`, f)),
			msg:  fmt.Sprintf(`"%s: field.field_path ${jsonencode(%s.field.field_path)} is not a Downward API field"`, n, ref),
		})
	}
	if has(srcs, "resource_field") {
		f := ref + ".resource_field"
		out = append(out, check{
			cond: guard(ref, f, fmt.Sprintf(`contains(["limits.cpu", "limits.memory", "limits.ephemeral-storage", "requests.cpu", "requests.memory", "requests.ephemeral-storage"], %s.resource)`, f)),
			msg:  fmt.Sprintf(`"%s: resource_field.resource ${jsonencode(%s.resource_field.resource)} is not a container resource"`, n, ref),
		})
	}
	if !v.Secret {
		val := ref + ".value"
		for _, c := range valueChecks(v, val) {
			out = append(out, check{cond: guard(ref, val, c.cond), msg: c.msg})
		}
	}
	for i := range out {
		out[i].msg = safeMessage(out[i].msg)
	}
	return out
}

// safeMessage wraps each interpolation in an error message in try():
// Terraform evaluates a message even when its condition holds, and then
// the value it names can be null.
func safeMessage(msg string) string {
	var b strings.Builder
	for i := 0; i < len(msg); i++ {
		if msg[i] == '$' && i+1 < len(msg) && msg[i+1] == '$' {
			b.WriteString("$$")
			i++
			continue
		}
		if msg[i] != '$' || i+1 >= len(msg) || msg[i+1] != '{' {
			b.WriteByte(msg[i])
			continue
		}
		depth, j := 1, i+2
		for ; j < len(msg) && depth > 0; j++ {
			switch msg[j] {
			case '{':
				depth++
			case '}':
				depth--
			}
		}
		fmt.Fprintf(&b, `${try(format("%%v", %s), "")}`, msg[i+2:j-1])
		i = j - 1
	}
	return b.String()
}

const (
	qualifiedName = `can(regex("^([a-z0-9]([-a-z0-9]*[a-z0-9])?(\\.[a-z0-9]([-a-z0-9]*[a-z0-9])?)*/)?[A-Za-z0-9]([-A-Za-z0-9_.]{0,61}[A-Za-z0-9])?$", k)) && can(regex("^([^/]{1,253}/)?[^/]+$", k))`
	labelValue    = `can(regex("^([A-Za-z0-9]([-A-Za-z0-9_.]{0,61}[A-Za-z0-9])?)?$", x))`
	placeholder   = `length(regexall("\\{(input|path|dir|file)\\}", "${k}${x}")) > 0`
	qualifiedText = `an optional DNS-subdomain prefix (at most 253 characters) and \"/\", then at most 63 letters, digits, \"-\", \"_\" and \".\", starting and ending with a letter or digit`
)

// podChecks validates pod annotations and labels (#PodMetadata): keys are
// qualified names and label values are label values. Entries that still
// hold a placeholder are reported by another check. prefix starts each
// message; wrap guards each condition.
func podChecks(prefix, ann, lab string, wrap func(string) string) []check {
	key := func(kind, m string) check {
		return check{
			wrap(fmt.Sprintf("alltrue([for k, x in %s : %s || %s])", m, placeholder, qualifiedName)),
			fmt.Sprintf(`"%spod %s key ${jsonencode([for k, x in %s : k if !(%s || %s)][0])} is not a Kubernetes qualified name: %s"`, prefix, kind, m, placeholder, qualifiedName, qualifiedText),
		}
	}
	return []check{
		key("annotation", ann),
		key("label", lab),
		{
			wrap(fmt.Sprintf("alltrue([for k, x in %s : %s || %s])", lab, placeholder, labelValue)),
			fmt.Sprintf(`"%spod label ${[for k, x in %s : k if !(%s || %s)][0]}: value ${jsonencode([for k, x in %s : x if !(%s || %s)][0])} is not a label value: at most 63 letters, digits, \"-\", \"_\" and \".\", starting and ending with a letter or digit, or empty"`,
				prefix, lab, placeholder, labelValue, lab, placeholder, labelValue),
		},
	}
}

// guard makes cond apply only when ref and attr are set.
func guard(ref, attr, cond string) string {
	return fmt.Sprintf("%s == null ? true : (%s == null ? true : %s)", ref, attr, cond)
}

// codePoints counts characters as the spec does, in code points. HCL's
// length() counts grapheme clusters, so it is not used for strings.
func codePoints(s string) string {
	return fmt.Sprintf(`length(regexall("(?s).", %s))`, s)
}

func valueChecks(v Var, x string) []check {
	n := v.Name
	r := v.Raw
	q := fmt.Sprintf("${jsonencode(%s)}", x)
	var out []check
	switch v.Type {
	case "string":
		if m, ok := num(r, "minLength"); ok {
			out = append(out, check{codePoints(x) + " >= " + m, fmt.Sprintf(`"%s: %s is ${%s} characters, below minLength %s"`, n, q, codePoints(x), m)})
		}
		if m, ok := num(r, "maxLength"); ok {
			out = append(out, check{codePoints(x) + " <= " + m, fmt.Sprintf(`"%s: %s is ${%s} characters, above maxLength %s"`, n, q, codePoints(x), m)})
		}
		if p := str(r, "pattern"); p != "" {
			out = append(out, check{fmt.Sprintf("can(regex(%s, %s))", hclString(p), x), fmt.Sprintf(`"%s: %s does not match pattern %s"`, n, q, lit(p))})
		}
	case "int":
		out = append(out, check{fmt.Sprintf("floor(%s) == %s", x, x), fmt.Sprintf(`"%s: expected an integer, got ${%s}"`, n, x)})
		if m, ok := num(r, "min"); ok {
			out = append(out, check{x + " >= " + m, fmt.Sprintf(`"%s: ${%s} is below min %s"`, n, x, m)})
		}
		if m, ok := num(r, "max"); ok {
			out = append(out, check{x + " <= " + m, fmt.Sprintf(`"%s: ${%s} is above max %s"`, n, x, m)})
		}
	case "float":
		if m, ok := num(r, "min"); ok {
			out = append(out, check{x + " >= " + m, fmt.Sprintf(`"%s: ${%s} is below min %s"`, n, x, m)})
		}
		if m, ok := num(r, "max"); ok {
			out = append(out, check{x + " <= " + m, fmt.Sprintf(`"%s: ${%s} is above max %s"`, n, x, m)})
		}
	case "duration":
		out = append(out, check{fmt.Sprintf(`can(regex("^([0-9]+(ns|us|ms|s|m|h))+$", %s))`, x), fmt.Sprintf(`"%s: %s is not a duration such as 1m30s"`, n, q)})
		ns := durationNanos(x)
		valid := fmt.Sprintf(`!can(regex("^([0-9]+(ns|us|ms|s|m|h))+$", %s)) ? true : `, x)
		if enc := str(r, "encoding"); enc != "" && enc != "go" {
			out = append(out, check{valid + fmt.Sprintf("%s %% 1000000 == 0", ns), fmt.Sprintf(`"%s: ${%s} is finer than a millisecond, which the %s encoding cannot carry"`, n, x, enc)})
		}
		if m := str(r, "min"); m != "" {
			out = append(out, check{valid + fmt.Sprintf("%s >= %s", ns, goNanos(m)), fmt.Sprintf(`"%s: ${%s} is below min %s"`, n, x, m)})
		}
		if m := str(r, "max"); m != "" {
			out = append(out, check{valid + fmt.Sprintf("%s <= %s", ns, goNanos(m)), fmt.Sprintf(`"%s: ${%s} is above max %s"`, n, x, m)})
		}
	case "url":
		out = append(out, check{fmt.Sprintf(`can(regex("^[a-zA-Z][a-zA-Z0-9+.-]*://[^\\s]+$", %s))`, x), fmt.Sprintf(`"%s: %s is not a URL of the form scheme://..."`, n, q)})
		if schemes := strs(r, "schemes"); len(schemes) > 0 {
			quoted := make([]string, len(schemes))
			for i, s := range schemes {
				quoted[i] = hclString(s)
			}
			out = append(out, check{
				fmt.Sprintf(`!can(regex("^[a-zA-Z][a-zA-Z0-9+.-]*://", %s)) ? true : contains([%s], split("://", %s)[0])`, x, strings.Join(quoted, ", "), x),
				fmt.Sprintf(`"%s: scheme ${jsonencode(split("://", %s)[0])} is not one of %s"`, n, x, lit(strings.Join(schemes, ", "))),
			})
		}
		if m, ok := num(r, "maxLength"); ok {
			out = append(out, check{codePoints(x) + " <= " + m, fmt.Sprintf(`"%s: %s is ${%s} characters, above maxLength %s"`, n, q, codePoints(x), m)})
		}
	case "enum":
		values := strs(r, "values")
		quoted := make([]string, len(values))
		for i, s := range values {
			quoted[i] = hclString(s)
		}
		out = append(out, check{fmt.Sprintf("contains([%s], %s)", strings.Join(quoted, ", "), x), fmt.Sprintf(`"%s: %s is not one of %s"`, n, q, lit(strings.Join(values, ", ")))})
	case "list":
		item := func(cond, msg string) check {
			// msg describes the first failing item, i, with value x.
			return check{
				fmt.Sprintf("alltrue([for i, x in %s : %s])", x, cond),
				fmt.Sprintf(`"%s: ${[for i, x in %s : "item ${i}: %s" if !(%s)][0]}"`, n, x, msg, cond),
			}
		}
		if str(r, "items") == "int" {
			out = append(out, item("floor(x) == x", "expected an integer, got ${x}"))
		}
		if m, ok := num(r, "minItems"); ok {
			out = append(out, check{fmt.Sprintf("length(%s) >= %s", x, m), fmt.Sprintf(`"%s: has ${length(%s)} items, below minItems %s"`, n, x, m)})
		}
		if m, ok := num(r, "maxItems"); ok {
			out = append(out, check{fmt.Sprintf("length(%s) <= %s", x, m), fmt.Sprintf(`"%s: has ${length(%s)} items, above maxItems %s"`, n, x, m)})
		}
		// Bounds are checked on integer items only; a fraction fails above.
		if m, ok := num(r, "itemMin"); ok {
			out = append(out, item(fmt.Sprintf("floor(x) != x || x >= %s", m), "${x} is below itemMin "+m))
		}
		if m, ok := num(r, "itemMax"); ok {
			out = append(out, item(fmt.Sprintf("floor(x) != x || x <= %s", m), "${x} is above itemMax "+m))
		}
		if m, ok := num(r, "itemMinLength"); ok {
			out = append(out, item(codePoints("x")+" >= "+m, fmt.Sprintf("${jsonencode(x)} is ${%s} characters, below itemMinLength %s", codePoints("x"), m)))
		}
		if m, ok := num(r, "itemMaxLength"); ok {
			out = append(out, item(codePoints("x")+" <= "+m, fmt.Sprintf("${jsonencode(x)} is ${%s} characters, above itemMaxLength %s", codePoints("x"), m)))
		}
	case "json":
		if m, ok := num(r, "maxLength"); ok {
			out = append(out, check{codePoints(compactJSON(x)) + " <= " + m, fmt.Sprintf(`"%s: is ${%s} characters as compact JSON, above maxLength %s"`, n, codePoints(compactJSON(x)), m)})
		}
	}
	return out
}

var durationUnits = `{ ns = 1, us = 1000, ms = 1000000, s = 1000000000, m = 60000000000, h = 3600000000000 }`

// durationNanos is an HCL expression for a Go-syntax duration's length in
// nanoseconds. Terraform numbers are arbitrary precision, so it is exact.
func durationNanos(x string) string {
	return fmt.Sprintf(`sum([for p in regexall("([0-9]+)(ns|us|ms|s|m|h)", %s) : tonumber(p[0]) * %s[p[1]]])`, x, durationUnits)
}

var unitNanos = map[string]int64{"ns": 1, "us": 1e3, "ms": 1e6, "s": 1e9, "m": 60e9, "h": 3600e9}
var durationPart = regexp.MustCompile(`([0-9]+)(ns|us|ms|s|m|h)`)

// goNanos is the length of a Go-syntax duration from the contract, in
// nanoseconds, as an HCL number literal.
func goNanos(d string) string {
	total := new(big.Int)
	for _, m := range durationPart.FindAllStringSubmatch(d, -1) {
		n, _ := new(big.Int).SetString(m[1], 10)
		total.Add(total, n.Mul(n, big.NewInt(unitNanos[m[2]])))
	}
	return total.String()
}

// compactJSON is an HCL expression for a value's compact JSON as #Render
// writes it. jsonencode escapes <, > and & as \uXXXX, which #Render does
// not (SPEC.md 4.3), so they are restored; U+2028 and U+2029 stay escaped,
// as #Render leaves them. An escaped backslash is set aside first, as a
// NUL, which jsonencode never writes raw, so a literal backslash before
// "u003c" is left alone.
func compactJSON(x string) string {
	s := fmt.Sprintf(`replace(jsonencode(%s), "\\\\", "\u0000")`, x)
	for _, r := range [][2]string{{`\\u003c`, "<"}, {`\\u003e`, ">"}, {`\\u0026`, "&"}} {
		s = fmt.Sprintf(`replace(%s, "%s", "%s")`, s, r[0], r[1])
	}
	return fmt.Sprintf(`replace(%s, "\u0000", "\\\\")`, s)
}

// esc doubles $ in an env value: the kubelet expands $(VAR) and reduces
// $$ to $ (SPEC.md 5).
func esc(x string) string { return fmt.Sprintf(`replace(%s, "$", "$$")`, x) }

// renderValue is an HCL expression for the list of env entries a literal
// renders to, in the variable's wire encoding.
func renderValue(v Var, x string) string {
	entry := func(name, value string) string {
		return fmt.Sprintf("{ name = %s, value = %s, value_from = null }", name, value)
	}
	n := hclString(v.Name)
	switch v.Type {
	case "json":
		return "[" + entry(n, esc(compactJSON(x))) + "]"
	case "list":
		switch str(v.Raw, "encoding") {
		case "json":
			return "[" + entry(n, esc(compactJSON(x))) + "]"
		case "indexed":
			return fmt.Sprintf(`[for i, item in %s : { name = "%s__${i}", value = %s, value_from = null }]`, x, v.Name, esc("tostring(item)"))
		default:
			sep := ","
			if s, ok := v.Raw["separator"].(string); ok {
				sep = s
			}
			return "[" + entry(n, esc(fmt.Sprintf("join(%s, [for item in %s : tostring(item)])", hclString(sep), x))) + "]"
		}
	case "duration":
		return "[" + entry(n, renderDuration(x, str(v.Raw, "encoding"))) + "]"
	}
	return "[" + entry(n, esc(fmt.Sprintf("tostring(%s)", x))) + "]"
}

// renderDuration mirrors #RenderDuration in the meta-schema.
func renderDuration(x, enc string) string {
	if enc == "" || enc == "go" {
		return x
	}
	ms := fmt.Sprintf("floor(%s / 1000000)", durationNanos(x))
	secs := fmt.Sprintf("floor(%s / 1000)", ms)
	frac := fmt.Sprintf("(%s %% 1000)", ms)
	fracStr := fmt.Sprintf(`(%s == 0 ? "" : ".${replace(format("%%03d", %s), "/0+$/", "")}")`, frac, frac)
	switch enc {
	case "seconds":
		return fmt.Sprintf(`"${%s}${%s}"`, secs, fracStr)
	case "iso8601":
		return fmt.Sprintf(`"PT${%s}${%s}S"`, secs, fracStr)
	default: // timespan
		days := fmt.Sprintf("floor(%s / 86400)", secs)
		return fmt.Sprintf(`"${%s > 0 ? "${%s}." : ""}${format("%%02d", floor(%s %% 86400 / 3600))}:${format("%%02d", floor(%s %% 3600 / 60))}:${format("%%02d", %s %% 60)}${%s}"`,
			days, days, secs, secs, secs, fracStr)
	}
}

func (g *gen) render() []byte {
	var b strings.Builder
	b.WriteString(Header)
	b.WriteString("\n# Each input's env entries, in its wire encoding (SPEC.md 5), as #Render writes them.\nlocals {\n")
	for _, v := range g.c.Vars {
		ref := "var." + v.Name
		n := hclString(v.Name)
		srcs := g.sources(v)
		injected := fmt.Sprintf(`%s.injected.ref == null ? [] : [{ name = %s, value = %s, value_from = null }]`, ref, n, esc(ref+".injected.ref"))
		var vf []string
		for _, kv := range [][2]string{{"secret_key_ref", "secret"}, {"config_map_key_ref", "config_map"}, {"field_ref", "field"}, {"resource_field_ref", "resource_field"}} {
			if has(srcs, kv[1]) {
				vf = append(vf, fmt.Sprintf("%s = %s.%s", kv[0], ref, kv[1]))
			} else {
				vf = append(vf, kv[0]+" = null")
			}
		}
		reference := fmt.Sprintf("[{ name = %s, value = null, value_from = { %s } }]", n, strings.Join(vf, ", "))
		expr := reference
		if has(srcs, "value") {
			expr = fmt.Sprintf("%s.value != null ? %s : %s", ref, renderValue(v, ref+".value"), reference)
		}
		fmt.Fprintf(&b, "  env_%s = %s == null ? [] : (%s.injected != null ? (%s) : (%s))\n", v.Name, ref, ref, injected, expr)
	}
	var envs []string
	for _, v := range g.c.Vars {
		envs = append(envs, "local.env_"+v.Name)
	}
	fmt.Fprintf(&b, "\n  kubernetes_env = flatten([%s])\n", strings.Join(envs, ", "))

	// Pod metadata of injected inputs, with {input} expanded (SPEC.md 4.5.2).
	b.WriteString("\n  # Pod annotations and labels each injected input asks for, after placeholder expansion.\n")
	var ann, lab []string
	for _, v := range g.c.Vars {
		for _, kind := range []string{"annotations", "labels"} {
			fmt.Fprintf(&b, "  pod_%s_%s = try({ for k, x in var.%s.injected.pod_%s : replace(k, \"{input}\", %q) => replace(x, \"{input}\", %q) }, {})\n",
				kind, v.Name, v.Name, kind, v.Name, v.Name)
		}
		ann = append(ann, "local.pod_annotations_"+v.Name)
		lab = append(lab, "local.pod_labels_"+v.Name)
	}
	fmt.Fprintf(&b, "  pod_annotation_sources = [var.docuconf_options.pod_annotations, %s]\n", strings.Join(ann, ", "))
	fmt.Fprintf(&b, "  pod_label_sources      = [var.docuconf_options.pod_labels, %s]\n", strings.Join(lab, ", "))
	b.WriteString("  pod_annotations        = merge(local.pod_annotation_sources...)\n")
	b.WriteString("  pod_labels             = merge(local.pod_label_sources...)\n")

	b.WriteString("\n  # How each input is set (spec/IAC.md 4.5); docuconf lint reads it.\n  bindings = {\n")
	for _, v := range g.c.Vars {
		var arms []string
		for _, s := range g.sources(v) {
			arms = append(arms, fmt.Sprintf("var.%s.%s != null ? %q", v.Name, s, s))
		}
		fmt.Fprintf(&b, "    %s = { set = var.%s != null, source = var.%s == null ? null : (%s : null) }\n", v.Name, v.Name, v.Name, strings.Join(arms, " : "))
	}
	b.WriteString("  }\n}\n")
	return []byte(b.String())
}

