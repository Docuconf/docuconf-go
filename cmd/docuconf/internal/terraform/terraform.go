func exampleValue(v Var) string {
	if d, ok := v.Raw["default"]; ok {
		if b, err := json.Marshal(d); err == nil {
			return string(b)
		}
	}
	switch v.Type {
	case "int", "float":
		if m, ok := num(v.Raw, "min"); ok {
			return m
		}
		return "1"
	case "bool":
		return "true"
	case "list":
		return "[]"
	case "enum":
		if vs := strs(v.Raw, "values"); len(vs) > 0 {
			return hclString(vs[0])
		}
	case "url":
		if s := strs(v.Raw, "schemes"); len(s) > 0 {
			return hclString(s[0] + "://example")
		}
		return `"https://example"`
	case "duration":
		return `"30s"`
	}
	return `"..."`
}

// hclString quotes s as an HCL string literal, escaping template
// sequences so the text is taken literally.
func hclString(s string) string {
	b, _ := json.Marshal(s)
	q := string(b)
	// encoding/json escapes <, > and & for HTML; HCL reads < fine, but
	// the plain characters are clearer.
	q = strings.NewReplacer(`\u003c`, "<", `\u003e`, ">", `\u0026`, "&").Replace(q)
	return escapeTemplate(q)
}

// lit is s as text inside an HCL quoted string: hclString without the
// quotes.
func lit(s string) string {
	q := hclString(s)
	return q[1 : len(q)-1]
}

// escapeTemplate keeps ${ and %{ from starting an HCL template sequence.
func escapeTemplate(s string) string {
	return strings.NewReplacer("${", "$${", "%{", "%%{").Replace(s)
}

func orList(s []string) string {
	if len(s) < 2 {
		return strings.Join(s, "")
	}
	return strings.Join(s[:len(s)-1], ", ") + " or " + s[len(s)-1]
}

func has(s []string, x string) bool {
	for _, y := range s {
		if y == x {
			return true
		}
	}
	return false
}

func str(m map[string]any, k string) string {
	s, _ := m[k].(string)
	return s
}

func boolean(m map[string]any, k string) bool {
	b, _ := m[k].(bool)
	return b
}

func num(m map[string]any, k string) (string, bool) {
	switch n := m[k].(type) {
	case json.Number:
		return n.String(), true
	case float64:
		return fmt.Sprint(n), true
	}
	return "", false
}

func strs(m map[string]any, k string) []string {
	l, _ := m[k].([]any)
	var out []string
	for _, x := range l {
		if s, ok := x.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

var versionField = regexp.MustCompile(`("generator":\s*\{[^{}]*?"version":\s*)"[^"]*"`)

// MaskVersion blanks the generator version in docuconf.json, so -check
// does not fail only because a newer docuconf made the module.
func MaskVersion(name string, data []byte) []byte {
	if name != "docuconf.json" {
		return data
	}
	return versionField.ReplaceAll(data, []byte(`${1}""`))
}
