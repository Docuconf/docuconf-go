// example is the usage's arguments: each required input, with a source.
func (g *gen) example() string {
	var b strings.Builder
	for _, v := range g.c.Vars {
		if !g.required(v) {
			continue
		}
		if v.Secret {
			fmt.Fprintf(&b, "  %s: { secretKeyRef: { name: %s, key: \"value\" } },\n", prop(v.Name), tsString(strings.ToLower(strings.ReplaceAll(v.Name, "_", "-"))))
			continue
		}
		fmt.Fprintf(&b, "  %s: { value: %s },\n", prop(v.Name), exampleValue(v))
	}
	if b.Len() == 0 {
		b.WriteString("  // every input is optional\n")
	}
	return b.String()
}

func exampleValue(v terraform.Var) string {
	if d, ok := v.Raw["default"]; ok {
		b, _ := json.Marshal(d)
		return string(b)
	}
	switch v.Type {
	case "int", "float":
		return "1"
	case "bool":
		return "true"
	case "duration":
		return `"30s"`
	case "url":
		return `"https://example.com"`
	case "enum":
		if vs := strs(v.Raw, "values"); len(vs) > 0 {
			return tsString(vs[0])
		}
	case "list":
		return "[]"
	case "json":
		return "{}"
	}
	return `"…"`
}

func codeList(xs []string) string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = "`" + x + "`"
	}
	return strings.Join(out, ", ")
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}
