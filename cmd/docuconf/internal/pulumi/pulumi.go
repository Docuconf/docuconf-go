// describe is an input's description, with its type and flags.
func describe(raw map[string]any) string {
	d := str(raw, "description")
	var tags []string
	if boolean(raw, "required") {
		tags = append(tags, "required")
	}
	if boolean(raw, "secret") {
		tags = append(tags, "secret")
	}
	if t := str(raw, "type"); t != "" && t != "string" {
		tags = append(tags, t)
	}
	if len(tags) > 0 {
		d += " (" + strings.Join(tags, ", ") + ")"
	}
	return strings.TrimSpace(d)
}

func (g *gen) contractTS(digest string) ([]byte, error) {
	// Indented, keeping the contract's key order.
	var ordered bytes.Buffer
	if err := json.Indent(&ordered, bytes.TrimSpace(g.c.JSON), "", "  "); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(Header)
	fmt.Fprintf(&b, "\nimport type { Contract } from \"./runtime\";\n\n")
	fmt.Fprintf(&b, "/** The contract this component was generated from. */\n")
	fmt.Fprintf(&b, "export const contract: Contract = %s;\n\n", ordered.String())
	fmt.Fprintf(&b, "/** The sha256 of the contract's compact JSON. */\nexport const digest = %s;\n", tsString(digest))
	return []byte(b.String()), nil
}

