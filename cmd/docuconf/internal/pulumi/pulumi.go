// Package pulumi generates a Pulumi component from a contract (spec/IAC.md
// section 6): a local package the program imports, with no provider
// plugin. The component's arguments are typed by the contract; it renders
// them as docuconf render does and checks them before anything is
// rendered, with @docuconf/core, the engine the app itself runs at boot.
package pulumi

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"github.com/docuconf/docuconf-go/cmd/docuconf/internal/terraform"
)

// Header starts every generated TypeScript file.
const Header = "// Code generated by docuconf. DO NOT EDIT.\n"

//go:embed ts/runtime.ts
var runtimeTS []byte

// Versions of the packages a generated component depends on.
const (
	coreVersion   = "^0.1.0"
	pulumiVersion = "^3.0.0"
	yamlVersion   = "^2.4.0"
	tomlVersion   = "^1.3.0"
)

// Options configure a generated component.
type Options struct {
	// Lang is the component's language: typescript or go.
	Lang string
	// Package is a Go component's package name; by default the contract's
	// name, without separators, then "config".
	Package string
	// Target is the workload kind to render for: kubernetes, ecs,
	// cloudrun or containerapps. A component renders for one target, as a
	// module does.
	Target string
	// GeneratorVersion is the docuconf CLI's version, recorded in
	// docuconf.json.
	GeneratorVersion string
	// Image is the image the contract was pulled from, pinned by digest,
	// when it came from an OCI reference; docuconf.json records it.
	Image string
	// Warn, if set, receives what the generator leaves out: an optional
	// input the target cannot carry.
	Warn func(string)
}

// Generate writes the component's files, keyed by file name.
func Generate(c *terraform.Contract, opt Options) (map[string][]byte, error) {
	if opt.Lang == "" {
		opt.Lang = "typescript"
	}
	if opt.Target == "" {
		opt.Target = "kubernetes"
	}
	if opt.Lang != "typescript" && opt.Lang != "go" && opt.Lang != "python" {
		return nil, fmt.Errorf("-lang %q is not supported yet; supported: typescript, go, python", opt.Lang)
	}
	switch opt.Target {
	case "kubernetes", "ecs", "cloudrun", "containerapps", "lambda":
	default:
		return nil, fmt.Errorf("-target %q is not supported by docuconf pulumi yet; supported: kubernetes, ecs, cloudrun, containerapps, lambda", opt.Target)
	}
	if c.Name == "" {
		return nil, fmt.Errorf("the contract has no metadata.name")
	}
	for _, v := range c.Vars {
		switch v.Type {
		case "string", "int", "float", "bool", "duration", "url", "enum", "list", "json", "keySet":
		default:
			return nil, fmt.Errorf("%s: type %q is not supported by docuconf pulumi", v.Name, v.Type)
		}
	}
	for _, f := range c.Files {
		switch f.Type {
		case "config", "tls", "caBundle", "keystore", "text", "binary":
		default:
			return nil, fmt.Errorf("%s: file type %q is not supported by docuconf pulumi", f.Name, f.Type)
		}
	}
	g := &gen{c: c, class: className(c.Name), target: opt.Target}
	if err := g.targetFiles(opt.Warn); err != nil {
		return nil, err
	}
	if err := g.appSecretNames(); err != nil {
		return nil, err
	}
	if g.target == "lambda" {
		var reserved []string
		for _, v := range c.Vars {
			if terraform.LambdaReserved(v.Name) {
				reserved = append(reserved, v.Name)
			}
		}
		if len(reserved) > 0 {
			return nil, fmt.Errorf("the contract declares %s, which Lambda reserves and refuses in a function's configuration; rename them in the contract", strings.Join(reserved, ", "))
		}
	}
	digest := terraform.Digest(c.JSON)
	m := map[string]any{
		"apiVersion":     "docuconf.dev/v1alpha1",
		"kind":           "PulumiComponent",
		"generator":      map[string]any{"name": "docuconf", "version": opt.GeneratorVersion},
		"language":       opt.Lang,
		"targets":        []string{opt.Target},
		"contractDigest": digest,
		"contract":       json.RawMessage(c.JSON),
	}
	if opt.Image != "" {
		m["image"] = opt.Image
	}
	meta, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	if opt.Lang == "go" {
		return generateGo(c, opt, append(meta, '\n'), digest)
	}
	if opt.Lang == "python" {
		return g.generatePython(opt, append(meta, '\n'), digest)
	}
	contractTS, err := g.contractTS(digest)
	if err != nil {
		return nil, err
	}
	index := g.index()
	if g.target != "kubernetes" {
		index = g.indexTarget()
	}
	return map[string][]byte{
		"index.ts":      []byte(index),
		"runtime.ts":    runtimeTS,
		"contract.ts":   contractTS,
		"package.json":  g.packageJSON(),
		"docuconf.json": append(meta, '\n'),
		"README.md":     []byte(g.readmeFor("typescript")),
	}, nil
}

// readmeFor is the component's README: the kubernetes one, or the
// target's.
func (g *gen) readmeFor(lang string) string {
	if g.target == "kubernetes" {
		if lang == "go" {
			return ""
		}
		return g.readme()
	}
	name := platformName[g.target]
	var b strings.Builder
	fmt.Fprintf(&b, "%s# %s configuration component (Pulumi, %s, %s)\n\n", terraform.MarkdownHeader, g.c.Name, map[string]string{"typescript": "TypeScript", "go": "Go"}[lang], name)
	fmt.Fprintf(&b, "Generated by `docuconf pulumi -lang %s -target %s` from the `%s` contract. It takes one argument per input the target carries, checks it against the contract with the SDK the app runs at boot, and renders ", lang, g.target, g.c.Name)
	switch g.target {
	case "ecs":
		b.WriteString("a container definition's `environment` and `secrets`. ECS does not expand `$(VAR)`, so values are as the app reads them. A secret is a Secrets Manager ARN, a Parameter Store ARN, or the name of either in the task's own account and region; the task execution role must be allowed to read it.\n\n")
	case "lambda":
		b.WriteString("a Lambda function's environment variables, as a map for its `environment.variables`. Lambda resolves no secret references, so a secret input is injected: its `ref`, such as a Secrets Manager or Parameter Store ARN, is the value, and the function reads the secret itself, through the AWS Parameters and Secrets Lambda Extension or an SDK. Lambda does not expand `$(VAR)`, and allows 4 KB of environment variables, which the component checks.\n\n")
	case "containerapps":
		b.WriteString("a container app's secrets, its container's env, and a Secret volume and mount for each file input, in the shapes of azure-native's `app.ContainerApp`. A secret, or a file input, is a Key Vault secret ID, versioned or not, read by the `identity` given: `System` (the default) or a user-assigned identity's resource ID, which must be able to read it (the Key Vault Secrets User role). The component names the app secret it adds for each (`dc-…`). Container Apps expands `$(VAR)` in env values, so values are `$`-escaped, as on Kubernetes.\n\n")
	default:
		b.WriteString("a Cloud Run (v2) container's env, and the secret volumes and mounts of its file inputs. A secret, or a file input, is a Secret Manager secret, by ID or as `projects/PROJECT/secrets/SECRET`, at version `latest` unless given; the revision's service account must be allowed to access it.\n\n")
	}
	b.WriteString("| Input | Type | Required | Set with | Description |\n|---|---|---|---|---|\n")
	for _, v := range g.c.Vars {
		req := ""
		if boolean(v.Raw, "required") && !g.profileSupplies(v) {
			req = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", v.Name, v.Type, req, codeList(g.targetSources(v)), cell(str(v.Raw, "description")))
	}
	for _, f := range g.files {
		req := ""
		if boolean(f.Raw, "required") {
			req = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s file at `%s` | %s | `secret`, `injected` | %s |\n", f.Name, f.Type, str(f.Raw, "path"), req, cell(str(f.Raw, "description")))
	}
	return b.String()
}

// platformName is how a README and a message name a target's platform.
var platformName = map[string]string{"ecs": "Amazon ECS", "cloudrun": "Cloud Run", "containerapps": "Azure Container Apps", "lambda": "AWS Lambda"}

// appSecretNames refuses, on containerapps, two inputs whose names fold to
// the same app secret, as docuconf terraform does.
func (g *gen) appSecretNames() error {
	if g.target != "containerapps" {
		return nil
	}
	seen := map[string]string{}
	claim := func(secret, input string) error {
		if other, ok := seen[secret]; ok {
			return fmt.Errorf("inputs %s and %s would both be the Container Apps secret %s; rename one", other, input, secret)
		}
		seen[secret] = input
		return nil
	}
	for _, v := range g.c.Vars {
		if v.Secret && str(v.Raw, "encoding") != "indexed" {
			if err := claim(terraform.VarSecretName(v), v.Name); err != nil {
				return err
			}
		}
	}
	for _, f := range g.files {
		if err := claim(terraform.FileSecretName(f), f.Name); err != nil {
			return err
		}
	}
	return nil
}

type gen struct {
	c      *terraform.Contract
	class  string
	target string
	files  []terraform.File // the file inputs the target delivers
}

// targetFiles finds the file inputs the target delivers, as docuconf
// terraform does: ECS mounts none, Cloud Run all but tls directories, and
// neither has overlays. An optional input left out is a warning; a
// required one an error.
func (g *gen) targetFiles(warn func(string)) error {
	if warn == nil {
		warn = func(string) {}
	}
	var required []string
	for _, f := range g.c.Files {
		switch {
		case g.target == "kubernetes", (g.target == "cloudrun" || g.target == "containerapps") && f.Type != "tls":
			g.files = append(g.files, f)
		case boolean(f.Raw, "required"):
			required = append(required, f.Name)
		case g.target == "ecs":
			warn(fmt.Sprintf("%s: ECS mounts no files, so the ecs component leaves this optional file input out", f.Name))
		case g.target == "lambda":
			warn(fmt.Sprintf("%s: Lambda mounts no files, so the lambda component leaves this optional file input out", f.Name))
		case g.target == "containerapps":
			warn(fmt.Sprintf("%s: a tls input is a directory of several files, and a Container Apps secret holds one, so the containerapps component leaves this optional input out", f.Name))
		default:
			warn(fmt.Sprintf("%s: a tls input is a directory of several files, and a Cloud Run secret volume holds one, so the cloudrun component leaves this optional input out", f.Name))
		}
	}
	if len(required) > 0 {
		if g.target == "ecs" || g.target == "lambda" {
			return fmt.Errorf("the %s target mounts no files, and the contract requires file inputs %s; deploy it on a target that can (kubernetes)", g.target, strings.Join(required, ", "))
		}
		what := "a Cloud Run secret volume holds one file"
		if g.target == "containerapps" {
			what = "a Container Apps secret holds one file"
		}
		return fmt.Errorf("%s, and the contract requires tls inputs %s, which are directories; deploy it on a target that can mount them (kubernetes)", what, strings.Join(required, ", "))
	}
	if g.target != "kubernetes" {
		for _, o := range g.c.Overlays {
			warn(fmt.Sprintf("overlay %s: %s has no ConfigMaps, so the %s component leaves this overlay out; set its variables in the environment", o.Name, map[string]string{"ecs": "ECS", "cloudrun": "Cloud Run", "containerapps": "Container Apps", "lambda": "Lambda"}[g.target], g.target))
		}
	}
	return nil
}

// targetSources is targetSources for the component's target: on lambda,
// which resolves no secret references, a secret is injected.
func (g *gen) targetSources(v terraform.Var) []string {
	if g.target == "lambda" && v.Secret {
		return []string{"injected"}
	}
	return targetSources(v)
}

// targetSources mirrors runtime.ts targetVarSources.
func targetSources(v terraform.Var) []string {
	if v.Secret && str(v.Raw, "encoding") == "indexed" {
		return []string{"injected"}
	}
	if v.Secret {
		return []string{"secret", "injected"}
	}
	return []string{"value", "injected"}
}

// indexTarget is index.ts for the ecs, cloudrun and containerapps targets.
func (g *gen) indexTarget() string {
	var b strings.Builder
	b.WriteString(Header)
	name := platformName[g.target]
	fmt.Fprintf(&b, `//
// The %s contract as a Pulumi component for the %s target
// (spec/IAC.md section 6). See README.md.

import * as pulumi from "@pulumi/pulumi";

import { contract, digest } from "./contract";
import * as runtime from "./runtime";

export { ConfigViolation } from "./runtime";
export type {
  Bindings,
  CloudRunEnv,
  CloudRunVolume,
  CloudRunVolumeMount,
  ContainerAppEnv,
  ContainerAppSecret,
  ContainerAppVolume,
  ContainerAppVolumeMount,
  EcsEnvironmentEntry,
  EcsSecretEntry,
} from "./runtime";

type In<T> = pulumi.Input<T>;
export type Json = null | boolean | number | string | Json[] | JsonObject;
export interface JsonObject {
  [key: string]: Json;
}

/** A literal value. */
export interface Value<T> {
  value: In<T>;
}
/** A value an injector supplies at runtime; ref, if given, is rendered verbatim as the value. */
export interface Injected {
  injected: { provider: string; ref?: In<string> };
}
`, g.c.Name, name)
	if g.target == "ecs" {
		b.WriteString(`/**
 * A secret ECS resolves when the task starts: valueFrom is a Secrets Manager
 * ARN, a Parameter Store ARN, or the name of either in the task's own account
 * and region. jsonKey, versionStage and versionId select from a Secrets
 * Manager secret, which they need the full ARN of.
 */
export interface Secret {
  secret: { valueFrom: In<string>; jsonKey?: string; versionStage?: string; versionId?: string };
}
`)
	} else if g.target == "lambda" {
		// Lambda resolves no secret references: a secret is Injected.
	} else if g.target == "containerapps" {
		b.WriteString(`/**
 * A Key Vault secret, by ID with or without a version, and the identity
 * that reads it: System (the default) or a user-assigned identity's
 * resource ID. The component adds it to the app's secrets.
 */
export interface Secret {
  secret: { keyVaultSecretId: In<string>; identity?: In<string> };
}
/** A file an injector writes at the input's path; nothing is mounted. */
export interface InjectedFile {
  injected: { provider: string };
}
`)
	} else {
		b.WriteString(`/** A Secret Manager secret, by ID or as projects/PROJECT/secrets/SECRET, and its version: latest by default. */
export interface Secret {
  secret: { secret: In<string>; version?: string };
}
/** A file an injector writes at the input's path; nothing is mounted. */
export interface InjectedFile {
  injected: { provider: string };
}
`)
	}
	fmt.Fprintf(&b, "\n/** The arguments of %s: one per input of the %s contract the %s target carries. */\n", g.class, g.c.Name, g.target)
	fmt.Fprintf(&b, "export interface %sArgs {\n", g.class)
	for _, v := range g.c.Vars {
		doc(&b, "  ", describe(v.Raw))
		var types []string
		for _, s := range g.targetSources(v) {
			switch s {
			case "value":
				types = append(types, "Value<"+valueType(v)+">")
			case "secret":
				types = append(types, "Secret")
			default:
				types = append(types, "Injected")
			}
		}
		opt := "?"
		if boolean(v.Raw, "required") && !g.profileSupplies(v) {
			opt = ""
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", prop(v.Name), opt, strings.Join(types, " | "))
	}
	for _, f := range g.files {
		doc(&b, "  ", describe(f.Raw)+" ("+str(f.Raw, "path")+")")
		opt := "?"
		if boolean(f.Raw, "required") {
			opt = ""
		}
		fmt.Fprintf(&b, "  %s%s: Secret | InjectedFile;\n", prop(f.Name), opt)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "/**\n * The %s contract's inputs, checked and rendered for %s. Construction\n * throws a ConfigViolation for arguments that break the contract; a value\n * that is an Output is checked when it resolves.\n */\n", g.c.Name, name)
	fmt.Fprintf(&b, "export class %s extends pulumi.ComponentResource {\n", g.class)
	if g.target == "ecs" {
		b.WriteString(`  /** The container definition's environment, each { name, value }. */
  readonly ecsEnvironment: pulumi.Output<runtime.EcsEnvironmentEntry[]>;
  /** The container definition's secrets, each { name, valueFrom }. */
  readonly ecsSecrets: pulumi.Output<runtime.EcsSecretEntry[]>;
`)
	} else if g.target == "lambda" {
		b.WriteString(`  /** The function's environment variables, for environment.variables. */
  readonly lambdaEnvironment: pulumi.Output<Record<string, string>>;
`)
	} else if g.target == "containerapps" {
		b.WriteString(`  /** The container's env entries, each { name, value } or { name, secretRef }. */
  readonly containerappEnv: pulumi.Output<runtime.ContainerAppEnv[]>;
  /** The app's secrets for secret inputs, for configuration.secrets. */
  readonly containerappSecrets: pulumi.Output<runtime.ContainerAppSecret[]>;
  /** The template's Secret volumes for file inputs. */
  readonly containerappVolumes: pulumi.Output<runtime.ContainerAppVolume[]>;
  /** The container's volume mounts. */
  readonly containerappVolumeMounts: pulumi.Output<runtime.ContainerAppVolumeMount[]>;
`)
	} else {
		b.WriteString(`  /** The container's env entries, for a Cloud Run (v2) service or job. */
  readonly cloudrunEnv: pulumi.Output<runtime.CloudRunEnv[]>;
  /** The revision's secret volumes for file inputs. */
  readonly cloudrunVolumes: pulumi.Output<runtime.CloudRunVolume[]>;
  /** The container's volume mounts. */
  readonly cloudrunVolumeMounts: pulumi.Output<runtime.CloudRunVolumeMount[]>;
`)
	}
	fmt.Fprintf(&b, `  /** For each input, whether it is set and by which source. docuconf lint reads it. */
  readonly bindings: runtime.Bindings;
  /** Resolves once every value has passed its checks; fails with a ConfigViolation otherwise. */
  readonly checked: pulumi.Output<boolean>;

  constructor(name: string, args: %[1]sArgs, opts?: pulumi.ComponentResourceOptions) {
    // The arguments are the component's inputs, so that a preview shows
    // them and docuconf lint pulumi can check them.
    super(%[2]s, name, { contract: { name: %[4]s, digest, target: %[3]q, language: "typescript" }, arguments: args }, opts);
    const out = runtime.forTarget(this, contract, %[3]q, args as unknown as Record<string, unknown>);
`, g.class, tsString("docuconf:"+g.c.Name+":Config"), g.target, tsString(g.c.Name))
	if g.target == "ecs" {
		b.WriteString("    this.ecsEnvironment = out.rendered.ecsEnvironment;\n    this.ecsSecrets = out.rendered.ecsSecrets;\n")
	} else if g.target == "lambda" {
		b.WriteString("    this.lambdaEnvironment = out.rendered.lambdaEnvironment;\n")
	} else if g.target == "containerapps" {
		b.WriteString("    this.containerappEnv = out.rendered.containerappEnv;\n    this.containerappSecrets = out.rendered.containerappSecrets;\n    this.containerappVolumes = out.rendered.containerappVolumes;\n    this.containerappVolumeMounts = out.rendered.containerappVolumeMounts;\n")
	} else {
		b.WriteString("    this.cloudrunEnv = out.rendered.cloudrunEnv;\n    this.cloudrunVolumes = out.rendered.cloudrunVolumes;\n    this.cloudrunVolumeMounts = out.rendered.cloudrunVolumeMounts;\n")
	}
	fmt.Fprintf(&b, `    this.bindings = out.bindings;
    this.checked = out.checked;
    // Registered so that a value that fails its checks when it resolves
    // fails the deployment, once, even if nothing uses the outputs.
    // The arguments again, for the policy pack: a stack policy sees a
    // component's outputs, not its inputs.
    this.registerOutputs({ bindings: out.bindings, checked: out.checked, contract: { name: %s, digest, target: %q, language: "typescript" }, arguments: args });
  }
}
`, tsString(g.c.Name), g.target)
	return b.String()
}

// className is the component's class: the contract's name in PascalCase,
// then Config ("orders-api" is OrdersApiConfig).
func className(name string) string {
	var b strings.Builder
	up := true
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "Service" + s
	}
	return s + "Config"
}

func str(m map[string]any, k string) string {
	s, _ := m[k].(string)
	return s
}

func boolean(m map[string]any, k string) bool {
	b, _ := m[k].(bool)
	return b
}

func strs(m map[string]any, k string) []string {
	l, _ := m[k].([]any)
	var out []string
	for _, x := range l {
		if s, ok := x.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

// tsString is s as a TypeScript string literal.
func tsString(s string) string {
	b, _ := json.Marshal(s)
	return strings.NewReplacer(`<`, "<", `>`, ">", `&`, "&").Replace(string(b))
}

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// prop is a property name, quoted when it is not an identifier.
func prop(name string) string {
	if identRe.MatchString(name) {
		return name
	}
	return tsString(name)
}

// valueType is a variable's literal in TypeScript.
func valueType(v terraform.Var) string {
	switch v.Type {
	case "int", "float":
		return "number"
	case "bool":
		return "boolean"
	case "enum":
		var q []string
		for _, x := range strs(v.Raw, "values") {
			q = append(q, tsString(x))
		}
		if len(q) == 0 {
			return "string"
		}
		return strings.Join(q, " | ")
	case "list":
		if str(v.Raw, "items") == "int" {
			return "number[]"
		}
		return "string[]"
	case "json":
		return "Json"
	}
	return "string"
}

// sources mirrors runtime.ts varSources.
func sources(v terraform.Var) []string {
	if v.Secret {
		return []string{"secretKeyRef", "injected"}
	}
	s := []string{"value"}
	if v.Type != "list" {
		s = append(s, "configMapKeyRef")
	}
	if v.Type == "string" {
		s = append(s, "fieldRef")
	}
	if v.Type == "int" {
		s = append(s, "resourceFieldRef")
	}
	return append(s, "injected")
}

// fileSources mirrors runtime.ts fileSources.
func fileSources(f terraform.File) []string {
	if f.Secret {
		if f.Type == "tls" {
			return []string{"secret", "certificate", "csi", "injected"}
		}
		return []string{"secret", "csi", "injected"}
	}
	var s []string
	if f.Type != "binary" {
		s = append(s, "inline")
	}
	s = append(s, "configMap", "secret")
	if f.Type == "tls" {
		s = append(s, "certificate")
	}
	return append(s, "csi", "image", "injected")
}

var sourceTypes = map[string]string{
	"secretKeyRef":     "SecretKeyRef",
	"configMapKeyRef":  "ConfigMapKeyRef",
	"fieldRef":         "FieldRef",
	"resourceFieldRef": "ResourceFieldRef",
	"injected":         "Injected",
}

func (g *gen) fileType(f terraform.File, s string) string {
	switch s {
	case "inline":
		if f.Type == "config" {
			return "InlineFile<string | JsonObject | Json[]>"
		}
		return "InlineFile<string>"
	case "configMap":
		return "ConfigMapFile"
	case "secret":
		if f.Type == "tls" {
			return "SecretDirectory"
		}
		return "SecretFile"
	case "certificate":
		return "CertificateFile"
	case "csi":
		return "CsiFile"
	case "image":
		return "ImageFile"
	}
	return "InjectedFile"
}

// profileSupplies reports whether some profile gives the variable a
// default, so the program need not.
func (g *gen) profileSupplies(v terraform.Var) bool {
	if p := g.c.Profiles; p != nil {
		for _, m := range p.Defaults {
			if _, ok := m[v.Name]; ok {
				return true
			}
		}
	}
	return false
}

// inOverlay reports whether an overlay can carry the variable.
func (g *gen) inOverlay(v terraform.Var) bool {
	if v.Secret || str(v.Raw, "configKey") == "" || (g.c.Profiles != nil && g.c.Profiles.Selector == v.Name) {
		return false
	}
	return len(g.c.Overlays) > 0
}

func (g *gen) required(v terraform.Var) bool {
	return boolean(v.Raw, "required") && !g.profileSupplies(v) && !g.inOverlay(v)
}

func doc(b *strings.Builder, indent, text string) {
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "*/", "* /")
	fmt.Fprintf(b, "%s/** %s */\n", indent, text)
}

