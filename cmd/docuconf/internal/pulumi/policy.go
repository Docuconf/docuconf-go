package pulumi

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/docuconf/docuconf-go/cmd/docuconf/internal/terraform"
)

//go:embed ts/policy.ts
var policyTS []byte

const policyVersion = "^1.0.0"

// PolicyOptions configure a generated policy pack.
type PolicyOptions struct {
	// Target is the workload kind the pack checks: kubernetes, ecs or
	// cloudrun.
	Target string
	// GeneratorVersion is the docuconf CLI's version, recorded in
	// docuconf.json.
	GeneratorVersion string
}

// GeneratePolicy writes a CrossGuard policy pack for a contract and a
// target (spec/IAC.md section 6.3): a stack policy, mandatory, that
// applies the linter's rules to every component of the contract and the
// workloads that take its env, and an advisory one for the warnings.
func GeneratePolicy(c *terraform.Contract, opt PolicyOptions) (map[string][]byte, error) {
	if opt.Target == "" {
		opt.Target = "kubernetes"
	}
	switch opt.Target {
	case "kubernetes", "ecs", "cloudrun":
	default:
		return nil, fmt.Errorf("-target %q is not supported by docuconf pulumi policy yet; supported: kubernetes, ecs, cloudrun", opt.Target)
	}
	if c.Name == "" {
		return nil, fmt.Errorf("the contract has no metadata.name")
	}
	digest := terraform.Digest(c.JSON)
	meta, err := json.MarshalIndent(map[string]any{
		"apiVersion":     "docuconf.dev/v1alpha1",
		"kind":           "PulumiPolicyPack",
		"generator":      map[string]any{"name": "docuconf", "version": opt.GeneratorVersion},
		"targets":        []string{opt.Target},
		"contractDigest": digest,
		"contract":       json.RawMessage(c.JSON),
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	var ordered bytes.Buffer
	if err := json.Indent(&ordered, bytes.TrimSpace(c.JSON), "", "  "); err != nil {
		return nil, err
	}
	name := "docuconf-" + c.Name
	pack := name + "-" + opt.Target

	var contract strings.Builder
	contract.WriteString(Header)
	contract.WriteString("\nimport type { PackContract } from \"./policy\";\n\n")
	contract.WriteString("/** The contract this policy pack was generated from. */\n")
	fmt.Fprintf(&contract, "export const contract: PackContract = %s;\n\n", ordered.String())
	fmt.Fprintf(&contract, "/** The sha256 of the contract's compact JSON. */\nexport const digest = %s;\n", tsString(digest))

	var index strings.Builder
	index.WriteString(Header)
	fmt.Fprintf(&index, `//
// The %[1]s contract's policy pack for the %[2]s target (spec/IAC.md
// section 6.3). See README.md.

import { PolicyPack } from "@pulumi/policy";

import { contract, digest } from "./contract";
import { checkStack, type Settings } from "./policy";

new PolicyPack(%[3]q, {
  policies: [
    {
      name: %[4]q,
      description: "The %[1]s contract's rules: each workload that takes a docuconf component's env gets what the contract declares, through the component (docuconf lint's errors).",
      enforcementLevel: "mandatory",
      configSchema: {
        properties: {
          unmanagedEnv: { type: "array", items: { type: "string" }, description: "Env names the platform sets for itself, such as a sidecar's." },
          allowEnvFrom: { type: "boolean", description: "Allow envFrom, whose keys the pack cannot see." },
        },
      },
      validateStack: (args, reportViolation) => {
        const settings = args.getConfig<Settings>();
        for (const f of checkStack(contract, digest, %[2]q, args.resources, settings)) if (f.level === "error") reportViolation(%[5]s, f.urn);
      },
    },
    {
      name: %[6]q,
      description: "The %[1]s contract's warnings: a component no workload takes (docuconf lint's warnings).",
      enforcementLevel: "advisory",
      validateStack: (args, reportViolation) => {
        for (const f of checkStack(contract, digest, %[2]q, args.resources)) if (f.level === "warning") reportViolation(%[5]s, f.urn);
      },
    },
  ],
});
`, c.Name, opt.Target, pack, name, "`${f.message} (${f.code})`", name+"-advisory")

	pkg, _ := json.MarshalIndent(map[string]any{
		"name":        pack,
		"version":     "0.0.0",
		"private":     true,
		"description": fmt.Sprintf("The %s contract's CrossGuard policy pack for %s. Generated by docuconf pulumi policy; do not edit.", c.Name, opt.Target),
		"main":        "index.ts",
		"dependencies": map[string]string{
			"@docuconf/core": coreVersion,
			"@pulumi/policy": policyVersion,
			"@pulumi/pulumi": pulumiVersion,
		},
		// Pulumi runs a TypeScript pack with ts-node, which needs them.
		"devDependencies": map[string]string{
			"@types/node": "^22.0.0",
			"typescript":  "^5.4.0",
		},
	}, "", "  ")

	files := map[string][]byte{
		"PulumiPolicy.yaml": []byte(fmt.Sprintf("# Code generated by docuconf. DO NOT EDIT.\nruntime:\n  name: nodejs\n  options:\n    typescript: true\ndescription: The %s contract's rules for the %s target, from docuconf.\n", c.Name, opt.Target)),
		"package.json":      append(pkg, '\n'),
		"tsconfig.json":     []byte(policyTSConfig),
		"index.ts":          []byte(index.String()),
		"contract.ts":       []byte(contract.String()),
		"policy.ts":         policyTS,
		"docuconf.json":     append(meta, '\n'),
		"README.md":         []byte(policyReadme(c.Name, opt.Target, pack, name)),
	}
	return files, nil
}

const policyTSConfig = `{
  "compilerOptions": {
    "strict": true,
    "target": "es2020",
    "module": "commonjs",
    "moduleResolution": "node",
    "esModuleInterop": true,
    "skipLibCheck": true,
    "outDir": "bin"
  },
  "files": ["index.ts"]
}
`

func policyReadme(contract, target, pack, policy string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s# %s policy pack (Pulumi CrossGuard, %s)\n\n", terraform.MarkdownHeader, contract, target)
	fmt.Fprintf(&b, "Generated by `docuconf pulumi policy -target %s` from the `%s` contract. It applies the rules `docuconf lint pulumi` applies to a preview ([spec/IAC.md](https://github.com/Docuconf/docuconf-go/blob/main/spec/IAC.md) sections 6.3 and 7.2) during `pulumi preview` and `pulumi up`, to every stack that uses a `%s` component generated from the same contract:\n\n", target, contract, contract)
	b.WriteString("- each workload whose app container takes a component's env sets no undeclared name (`undeclared_input`), no name twice (`duplicate_env`), no secret as a plain value (`secret_as_value`), and every name the component renders (`unbound_container`);\n")
	b.WriteString("- a value written into the container by hand passes the contract's checks, as the app would run them at boot (`invalid_value`);\n")
	b.WriteString("- file inputs are mounted where the app reads them, whole and read-only (`mount_mismatch`), the pod metadata an injector asks for is on the pod template (`pod_metadata_missing`), and `envFrom` is refused (`env_from_unchecked`);\n")
	b.WriteString("- a component generated from another version of the contract fails (`stale_module`).\n\n")
	fmt.Fprintf(&b, "`%s` is mandatory: its findings fail the update. `%s-advisory` reports a component no workload takes (`module_unused`).\n\n", policy, policy)
	b.WriteString("A workload whose containers are unknown at preview is not checked; the component checks the values when they resolve.\n\n")
	b.WriteString("## Use\n\n```sh\nnpm install\npulumi preview --policy-pack path/to/this/directory\n```\n\n")
	fmt.Fprintf(&b, "Or publish it (`pulumi policy publish`) and enforce it from Pulumi Cloud. Settings, in a `--policy-pack-config` file:\n\n```json\n{ %q: { \"unmanagedEnv\": [\"OTEL_SERVICE_NAME\"], \"allowEnvFrom\": false } }\n```\n\n", policy)
	b.WriteString("Regenerate it rather than edit it when the contract changes.\n")
	return b.String()
}
