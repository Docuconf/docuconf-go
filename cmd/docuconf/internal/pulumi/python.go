//go:embed py/runtime.py
var runtimePy []byte

//go:embed py/sources.py
var sourcesPy []byte

// PythonHeader starts every generated Python file.
const PythonHeader = "# Code generated by docuconf. DO NOT EDIT.\n"

// pythonSDK is the docuconf Python SDK a Python component checks values
// with: from GitHub until it is on PyPI, pinned to a commit.
const pythonSDK = "docuconf-pydantic[tls,yaml,jsonschema] @ git+https://github.com/docuconf/docuconf-python@132e88cd0ee139d2d0a17fd63659a8455e0ff931"

var pyPackageRe = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

// pyPackage is a Python component's package name: by default the
// contract's name in snake_case, then _config.
func pyPackage(name, contract string) (string, error) {
	if name == "" {
		name = strings.Trim(regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(strings.ToLower(contract), "_"), "_") + "_config"
	}
	if !pyPackageRe.MatchString(name) {
		return "", fmt.Errorf("-package %q is not a Python package name: lowercase letters, digits and _", name)
	}
	return name, nil
}

func pyString(s string) string { return strconv.Quote(s) }

// pyValueType is a variable's literal in Python.
func pyValueType(v terraform.Var) string {
	switch v.Type {
	case "int":
		return "int"
	case "float":
		return "float"
	case "bool":
		return "bool"
	case "enum":
		var q []string
		for _, x := range strs(v.Raw, "values") {
			q = append(q, pyString(x))
		}
		if len(q) == 0 {
			return "str"
		}
		return "Literal[" + strings.Join(q, ", ") + "]"
	case "list":
		if str(v.Raw, "items") == "int" {
			return "List[int]"
		}
		return "List[str]"
	case "json":
		return "Json"
	}
	return "str"
}

var pySourceTypes = map[string]string{
	"secretKeyRef":     "SecretKeyRef",
	"configMapKeyRef":  "ConfigMapKeyRef",
	"fieldRef":         "FieldRef",
	"resourceFieldRef": "ResourceFieldRef",
	"injected":         "Injected",
}

func (g *gen) pyFileType(f terraform.File, s string) string {
	switch s {
	case "inline":
		if f.Type == "config" {
			return "InlineFile[Union[str, Dict[str, Any], List[Any]]]"
		}
		return "InlineFile[str]"
	case "configMap":
		return "ConfigMapFile"
	case "secret":
		if f.Type == "tls" {
			return "SecretDirectory"
		}
		return "SecretFile"
	case "certificate":
		return "CertificateFile"
	case "csi":
		return "CsiFile"
	case "image":
		return "ImageFile"
	}
	return "InjectedFile"
}

func pyComment(b *strings.Builder, indent, text string) {
	if text != "" {
		fmt.Fprintf(b, "%s# %s\n", indent, strings.ReplaceAll(text, "\n", " "))
	}
}

func union(types []string) string {
	if len(types) == 1 {
		return types[0]
	}
	return "Union[" + strings.Join(types, ", ") + "]"
}

// generatePython writes a Python component: the typed arguments
// (__init__.py), the shared runtime and sources, and the contract.
func (g *gen) generatePython(opt Options, meta []byte, digest string) (map[string][]byte, error) {
	pkg, err := pyPackage(opt.Package, g.c.Name)
	if err != nil {
		return nil, err
	}
	c := g.c
	var b strings.Builder
	b.WriteString(PythonHeader)
	fmt.Fprintf(&b, `"""The %s contract as a Pulumi component for the %s target (spec/IAC.md
section 6). See README.md."""

from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional, Union

import pulumi
from typing_extensions import Required, TypedDict

from . import runtime
from .contract import CONTRACT, DIGEST
from .runtime import ConfigViolation
from .sources import *  # noqa: F403

__all__ = [%q, %q, "ConfigViolation", "CONTRACT", "DIGEST"]

`, c.Name, g.target, g.class+"Args", g.class)

	// The arguments: one key per input, in the contract's names.
	fmt.Fprintf(&b, "%sArgs = TypedDict(\n    %q,\n    {\n", g.class, g.class+"Args")
	for _, v := range c.Vars {
		var types []string
		srcs := sources(v)
		if g.target != "kubernetes" {
			srcs = targetSources(v)
		}
		for _, s := range srcs {
			switch {
			case s == "value":
				types = append(types, "Value["+pyValueType(v)+"]")
			case g.target == "kubernetes":
				types = append(types, pySourceTypes[s])
			case s == "secret" && g.target == "ecs":
				types = append(types, "EcsSecret")
			case s == "secret" && g.target == "containerapps":
				types = append(types, "KeyVaultSecret")
			case s == "secret":
				types = append(types, "CloudRunSecret")
			default:
				types = append(types, "TargetInjected")
			}
		}
		t := union(types)
		required := g.required(v)
		if g.target != "kubernetes" {
			required = boolean(v.Raw, "required") && !g.profileSupplies(v)
		}
		if required {
			t = "Required[" + t + "]"
		}
		pyComment(&b, "        ", describe(v.Raw))
		fmt.Fprintf(&b, "        %s: %s,\n", pyString(v.Name), t)
	}
	for _, f := range g.files {
		var types []string
		if g.target == "kubernetes" {
			for _, s := range fileSources(f) {
				types = append(types, g.pyFileType(f, s))
			}
		} else if g.target == "containerapps" {
			types = []string{"KeyVaultSecret", "TargetInjectedFile"}
		} else {
			types = []string{"CloudRunSecret", "TargetInjectedFile"}
		}
		t := union(types)
		if boolean(f.Raw, "required") {
			t = "Required[" + t + "]"
		}
		pyComment(&b, "        ", describe(f.Raw)+" ("+str(f.Raw, "path")+")")
		fmt.Fprintf(&b, "        %s: %s,\n", pyString(f.Name), t)
	}
	if g.target == "kubernetes" {
		b.WriteString("        # Pod annotations and labels for the workload, beside the ones injected inputs ask for.\n")
		b.WriteString("        \"podMetadata\": pulumi.Input[PodMetadata],\n")
		if len(c.Overlays) > 0 {
			b.WriteString("        # Values to write into the contract's overlay files, by overlay: literals, never Outputs.\n")
			b.WriteString("        \"overlayValues\": Dict[str, Dict[str, Any]],\n")
		}
	}
	b.WriteString("    },\n    total=False,\n)\n\n\n")

	info := fmt.Sprintf(`{"name": %s, "digest": DIGEST, "target": %q, "language": "python"}`, pyString(c.Name), g.target)
	fmt.Fprintf(&b, "class %s(pulumi.ComponentResource):\n", g.class)
	if g.target == "kubernetes" {
		fmt.Fprintf(&b, `    """The %s contract's inputs, checked and rendered for a Kubernetes workload.
    Put kubernetes_env, kubernetes_volumes and kubernetes_volume_mounts in the
    container, pod_annotations and pod_labels on the pod template (never the
    workload), and declare a ConfigMap for each of kubernetes_config_maps.

    Construction raises a ConfigViolation for arguments that break the
    contract; a value that is an Output is checked when it resolves, and every
    output fails if it breaks the contract."""

    kubernetes_env: pulumi.Output[List[Dict[str, Any]]]
    """The container's env, as kubernetes.core.v1.EnvVarArgs dicts."""
    kubernetes_volumes: pulumi.Output[List[Dict[str, Any]]]
    """The pod's volumes for file inputs and overlays."""
    kubernetes_volume_mounts: pulumi.Output[List[Dict[str, Any]]]
    """The container's volume mounts."""
    kubernetes_config_maps: List[Dict[str, Any]]
    """ConfigMaps for inline file content and overlays, to declare in the workload's namespace: known now."""
    restart_triggers: pulumi.Output[List[Dict[str, Any]]]
    """The ConfigMaps, Secrets and SecretProviderClasses whose change must restart the pods."""
    pod_annotations: pulumi.Output[Dict[str, str]]
    """Annotations for the pod template's metadata."""
    pod_labels: pulumi.Output[Dict[str, str]]
    """Labels for the pod template's metadata."""
`, c.Name)
	} else {
		name := platformName[g.target]
		fmt.Fprintf(&b, `    """The %s contract's inputs, checked and rendered for %s.

    Construction raises a ConfigViolation for arguments that break the
    contract; a value that is an Output is checked when it resolves."""

`, c.Name, name)
		if g.target == "ecs" {
			b.WriteString("    ecs_environment: pulumi.Output[List[Dict[str, str]]]\n    \"\"\"The container definition's environment, each {name, value}.\"\"\"\n")
			b.WriteString("    ecs_secrets: pulumi.Output[List[Dict[str, str]]]\n    \"\"\"The container definition's secrets, each {name, valueFrom}.\"\"\"\n")
		} else if g.target == "containerapps" {
			b.WriteString("    containerapp_env: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The container's env, as azure-native app.EnvironmentVarArgs dicts.\"\"\"\n")
			b.WriteString("    containerapp_secrets: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The app's secrets for secret inputs, as app.SecretArgs dicts.\"\"\"\n")
			b.WriteString("    containerapp_volumes: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The template's Secret volumes for file inputs.\"\"\"\n")
			b.WriteString("    containerapp_volume_mounts: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The container's volume mounts.\"\"\"\n")
		} else {
			b.WriteString("    cloudrun_env: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The container's env, as cloudrunv2.ServiceTemplateContainerEnvArgs dicts.\"\"\"\n")
			b.WriteString("    cloudrun_volumes: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The revision's secret volumes for file inputs.\"\"\"\n")
			b.WriteString("    cloudrun_volume_mounts: pulumi.Output[List[Dict[str, Any]]]\n    \"\"\"The container's volume mounts.\"\"\"\n")
		}
	}
	b.WriteString(`    bindings: Dict[str, Dict[str, Any]]
    """For each input, whether it is set and by which source."""
    checked: pulumi.Output[bool]
    """Resolves once every value has passed its checks; fails with a ConfigViolation otherwise."""

`)
	fmt.Fprintf(&b, `    def __init__(self, resource_name: str, args: %[1]sArgs, opts: Optional[pulumi.ResourceOptions] = None) -> None:
        arguments = {k: v for k, v in dict(args).items() if v is not None}
        # The arguments are the component's inputs, so that a preview shows
        # them and docuconf lint pulumi can check them.
        super().__init__(%[2]q, resource_name, {"contract": %[3]s, "arguments": arguments}, opts)
`, g.class, "docuconf:"+c.Name+":Config", info)
	if g.target == "kubernetes" {
		b.WriteString(`        inputs = dict(arguments)
        pod_metadata = inputs.pop("podMetadata", None)
        overlay_values = inputs.pop("overlayValues", None)
        out = runtime.kubernetes(self, CONTRACT, inputs, overlay_values, pod_metadata)
        self.kubernetes_env = out["kubernetes_env"]
        self.kubernetes_volumes = out["kubernetes_volumes"]
        self.kubernetes_volume_mounts = out["kubernetes_volume_mounts"]
        self.kubernetes_config_maps = out["kubernetes_config_maps"]
        self.restart_triggers = out["restart_triggers"]
        self.pod_annotations = out["pod_annotations"]
        self.pod_labels = out["pod_labels"]
        self.bindings = out["bindings"]
        self.checked = out["checked"]
        extra = {"kubernetes_config_maps": out["kubernetes_config_maps"]}
`)
	} else {
		fmt.Fprintf(&b, "        out = runtime.for_target(self, CONTRACT, %q, arguments)\n        rendered = out[\"rendered\"]\n", g.target)
		if g.target == "ecs" {
			b.WriteString("        self.ecs_environment = rendered.apply(lambda r: r[\"ecs_environment\"])\n        self.ecs_secrets = rendered.apply(lambda r: r[\"ecs_secrets\"])\n")
		} else if g.target == "containerapps" {
			for _, o := range []string{"containerapp_env", "containerapp_secrets", "containerapp_volumes", "containerapp_volume_mounts"} {
				fmt.Fprintf(&b, "        self.%[1]s = rendered.apply(lambda r: r[%[1]q])\n", o)
			}
		} else {
			b.WriteString("        self.cloudrun_env = rendered.apply(lambda r: r[\"cloudrun_env\"])\n        self.cloudrun_volumes = rendered.apply(lambda r: r[\"cloudrun_volumes\"])\n        self.cloudrun_volume_mounts = rendered.apply(lambda r: r[\"cloudrun_volume_mounts\"])\n")
		}
		b.WriteString("        self.bindings = out[\"bindings\"]\n        self.checked = out[\"checked\"]\n        extra = {}\n")
	}
	fmt.Fprintf(&b, `        # Registered so that a value that fails its checks when it resolves
        # fails the deployment, once, even if nothing uses the outputs; the
        # arguments again, for the policy pack, which sees outputs.
        self.register_outputs({"bindings": self.bindings, "checked": self.checked, "contract": %s, "arguments": arguments, **extra})
`, info)

	var contract strings.Builder
	contract.WriteString(PythonHeader)
	contract.WriteString(`"""The contract this component was generated from, and its digest."""

import json
from pathlib import Path
from typing import Any, Dict

CONTRACT: Dict[str, Any] = json.loads((Path(__file__).parent / "contract.json").read_text(encoding="utf-8"))

`)
	fmt.Fprintf(&contract, "DIGEST = %s\n\"\"\"The sha256 of the contract's compact JSON.\"\"\"\n", pyString(digest))

	var indented bytes.Buffer
	if err := json.Indent(&indented, bytes.TrimSpace(c.JSON), "", "  "); err != nil {
		return nil, err
	}
	indented.WriteByte('\n')

	requirements := PythonHeader + "# What the component needs, beside the providers the program uses.\n" +
		"pulumi>=3.100,<4\n" + pythonSDK + "\nPyYAML>=6\ntomli-w>=1\ntyping-extensions>=4.6\n"

	return map[string][]byte{
		"__init__.py":      []byte(b.String()),
		"runtime.py":       runtimePy,
		"sources.py":       sourcesPy,
		"contract.py":      []byte(contract.String()),
		"contract.json":    indented.Bytes(),
		"requirements.txt": []byte(requirements),
		"docuconf.json":    meta,
		"README.md":        []byte(g.readmePython(pkg)),
	}, nil
}

func (g *gen) readmePython(pkg string) string {
	var b strings.Builder
	name := map[string]string{"kubernetes": "Kubernetes", "ecs": "Amazon ECS", "cloudrun": "Cloud Run", "containerapps": "Azure Container Apps"}[g.target]
	fmt.Fprintf(&b, "%s# %s configuration component (Pulumi, Python, %s)\n\n", terraform.MarkdownHeader, g.c.Name, name)
	fmt.Fprintf(&b, "Generated by `docuconf pulumi -lang python -target %s` from the `%s` contract. `%s` takes one argument per input, in the vocabulary of `values.yaml` (`{\"value\": ...}`, `{\"secretKeyRef\": {...}}`), checks each against the contract with the docuconf Python SDK, the engine a Python app runs at boot, and renders ", g.target, g.c.Name, g.class)
	switch g.target {
	case "kubernetes":
		b.WriteString("a container's `env`, volumes and mounts, the ConfigMaps for inline content and overlays, and the pod metadata injected inputs ask for, as the kubernetes provider's input dicts.\n\n")
	case "ecs":
		b.WriteString("a container definition's `environment` and `secrets`, for its JSON.\n\n")
	case "containerapps":
		b.WriteString("a container app's secrets, its container's env, and a Secret volume and mount for each file input, as azure-native's `app` input dicts. A secret is a Key Vault secret ID read by `System` or a user-assigned identity; values are `$`-escaped, since Container Apps expands `$(VAR)`.\n\n")
	default:
		b.WriteString("a Cloud Run (v2) container's env and the secret volumes and mounts of its file inputs, as the gcp provider's input dicts.\n\n")
	}
	fmt.Fprintf(&b, "Install what it needs (`pip install -r %s/requirements.txt`) and import it from the program's directory:\n\n", pkg)
	fmt.Fprintf(&b, "```python\nfrom %s import %s\n\norders = %s(\"orders\", {\n", pkg, g.class, g.class)
	n := 0
	for _, v := range g.c.Vars {
		if n == 3 {
			break
		}
		n++
		switch {
		case v.Secret && g.target == "kubernetes":
			fmt.Fprintf(&b, "    %q: {\"secretKeyRef\": {\"name\": \"app\", \"key\": %q}},\n", v.Name, strings.ToLower(v.Name))
		case v.Secret && g.target == "ecs":
			fmt.Fprintf(&b, "    %q: {\"secret\": {\"valueFrom\": \"arn:aws:secretsmanager:us-east-1:123456789012:secret:app\"}},\n", v.Name)
		case v.Secret:
			fmt.Fprintf(&b, "    %q: {\"secret\": {\"secret\": \"app\"}},\n", v.Name)
		default:
			fmt.Fprintf(&b, "    %q: {\"value\": ...},\n", v.Name)
		}
	}
	b.WriteString("})\n```\n\nA type checker (mypy, pyright) refuses a source an input does not accept, such as `{\"value\": ...}` for a secret; the component checks again when it is constructed. Regenerate it rather than edit it when the contract changes.\n")
	return b.String()
}
